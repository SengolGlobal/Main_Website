import type { Metadata } from 'next';
import { defaultLocale, localeInfo, locales, type Locale } from '@/i18n/locales';
import { siteUrl } from '@/data/site';

/** Absolute URL for a locale + path ('' for the locale home). */
export function localizedUrl(locale: Locale, path = '') {
  return `${siteUrl}/${locale}${path}`;
}

export function languageAlternates(path = '') {
  const languages: Record<string, string> = {};
  for (const l of locales) languages[localeInfo[l].hreflang] = localizedUrl(l, path);
  languages['x-default'] = localizedUrl(defaultLocale, path);
  return languages;
}

type BuildMetadataInput = {
  locale: Locale;
  path: string;
  title: string;
  description: string;
  siteName: string;
  /** Use the title as-is instead of appending the brand suffix. */
  absoluteTitle?: boolean;
  titleSuffix?: string;
  image?: string;
  noIndex?: boolean;
};

export function buildMetadata({
  locale,
  path,
  title,
  description,
  siteName,
  absoluteTitle,
  titleSuffix,
  image,
  noIndex,
}: BuildMetadataInput): Metadata {
  const fullTitle = absoluteTitle || !titleSuffix ? title : `${title} | ${titleSuffix}`;
  const url = localizedUrl(locale, path);
  // Default social card is generated by app/[locale]/opengraph-image.tsx. It is set
  // explicitly because a page-level `openGraph` object replaces inherited images.
  const images = [{ url: image ?? `${siteUrl}/${locale}/opengraph-image`, width: 1200, height: 630, alt: siteName }];
  return {
    title: { absolute: fullTitle },
    description,
    alternates: { canonical: url, languages: languageAlternates(path) },
    openGraph: {
      type: 'website',
      url,
      title: fullTitle,
      description,
      siteName,
      locale: localeInfo[locale].og,
      alternateLocale: locales.filter((l) => l !== locale).map((l) => localeInfo[l].og),
      images,
    },
    twitter: { card: 'summary_large_image', title: fullTitle, description, images: images.map((i) => i.url) },
    robots: noIndex ? { index: false, follow: true } : undefined,
  };
}
